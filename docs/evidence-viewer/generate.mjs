import { readFile, writeFile } from "node:fs/promises";
import { verifyEvidenceBundle } from "../../packages/operator/src/monitoring/evidence.ts";

async function summarize(path) {
  const proof = JSON.parse(await readFile(new URL("../../" + path, import.meta.url), "utf8"));
  const agreement = proof.agreement;
  const rows = await Promise.all(agreement.oracles.map(async (oracle, i) => {
    const bundle = proof.evidence.find(entry => entry.evidence.oracle === oracle);
    const { submitted, ...vote } = agreement.votes[i];
    if (!submitted || !bundle || !await verifyEvidenceBundle(bundle, {
      config: {
        network: proof.network, contract: proof.contract, sla_id: proof.sla_id, oracle,
        endpoint_hash: agreement.endpoint_hash, starts_at_ms: agreement.starts_at_ms,
        slot_ms: agreement.slot_ms, slot_count: agreement.slot_count
      },
      contract_vote: { sla_id: proof.sla_id, ...vote }
    })) throw new Error("Archived observation bundle does not match the vote for " + oracle);
    return { oracle, slots: bundle.evidence.observations.map(({ result, http_status }) => ({ result, status: http_status })) };
  }));
  return {
    path, rows, threshold: agreement.min_down_slots, verdict: proof.verdict,
    amount: proof.amount_yoctonear, beneficiary: proof.beneficiary ?? proof.customer,
    transaction: proof.transaction_hash, transfer: proof.transfer_receipt_id,
    callback: proof.callback_receipt_id, explorer: proof.explorer_url
  };
}

const cases = await Promise.all([
  summarize("examples/testnet/payment-proof.json"),
  summarize("examples/sandbox/inconclusive-proof.json")
]);
const output = "// Generated by generate.mjs from the archived proofs.\nconst evidenceCases = " + JSON.stringify(cases, null, 2) + ";\n";
const target = new URL("data.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (output !== await readFile(target, "utf8")) throw new Error("Evidence viewer data is stale. Run generate.mjs.");
} else {
  await writeFile(target, output);
}
